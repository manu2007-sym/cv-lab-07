import cv2
import numpy as np
import matplotlib.pyplot as plt

def filtered_image(img,kernel,p,s):
  rows = (img.shape[0]-kernel.shape[0]+2*p)//s+1
  cols = (img.shape[1]-kernel.shape[1]+2*p)//s+1
  output = np.zeros((rows,cols))
  if p == 0:
    padded_image=img
  else:
    padded_image = np.pad(img,p,constant_values=0)
  for i in range(rows):
    for j in range(cols):

      window = padded_image[i*s : i*s + kernel.shape[0], j*s : j*s + kernel.shape[1]]
      output[i][j] = np.sum(window * kernel)
  return output
img = cv2.imread("/content/lotus.jpg", 0)
k = 5
kernel = np.ones((k,k))/k**2
filtered_img = filtered_image(img,kernel,p=0,s=1)

plt.imshow(filtered_img, cmap='gray')
plt.title("Filtered Image")
plt.axis('off')
plt.show()